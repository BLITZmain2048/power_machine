@pytest.mark.parametrize('backend',['compatibility','numpy','lu'])
def test_dense_factor_solves_and_preserves_rhs(backend):
    matrix=np.array([[3.,1.],[1.,2.]])
    factor=LinearFactorization(matrix,backend)
    rhs=np.array([1.,-2.]);old=rhs.copy()
    np.testing.assert_allclose(matrix@factor.solve(rhs),rhs,atol=1e-14)
    np.testing.assert_array_equal(rhs,old)
    if backend=='numpy':assert factor.backend=='numpy'

def test_scipy_lu_without_inverse(monkeypatch):
    pytest.importorskip('scipy')
    monkeypatch.setattr(np.linalg,'inv',lambda *args:pytest.fail('LU must not form an inverse'))
    f=LinearFactorization(np.array([[3.,1.],[1.,2.]]),'scipy')
    np.testing.assert_allclose(f.solve(np.array([1.,0.])),[.4,-.2])
    assert f.backend=='scipy'

@pytest.mark.parametrize('backend',['compatibility','numpy'])
def test_newton_reuses_cached_factor(backend,monkeypatch):
    import power_machine.dynamics.solver as module
    solver,state=smib();solver.linear_solver=backend
    actual=module.LinearFactorization;seen=[]
    def record(matrix,option):seen.append(matrix.copy());return actual(matrix,option)
    monkeypatch.setattr(module,'LinearFactorization',record)
    m=np.array([[3.,1.],[1.,2.]])
    for rhs in (np.array([1.,0.]),np.array([2.,-1.])):
        out,*_=solver._newton(lambda u:m@u-rhs,np.zeros(2),np.full(2,1e-12),lambda u:m,cache_key=('test',backend))
        np.testing.assert_allclose(m@out,rhs,atol=1e-12)
    assert len(seen)==1
    solver.restart_discrete()
    assert solver._step_factor is None

@pytest.mark.parametrize('change',['step','topology','service','regime'])
def test_numpy_cache_key_invalidates_changes(change,monkeypatch):
    solver,state=smib(delta_offset=.02);solver.linear_solver='numpy'
    state,_=solver.step(state)
    key=solver._step_key
    if change=='step':h=solver.step_s/2
    else:h=solver.step_s
    if change=='topology':solver.network.rebuild()
    if change=='service':solver.in_service[solver.devices[1].object_id]=False
    if change=='regime':solver.devices[0].active_limit_signature=lambda:('changed',)
    # Inspect the actual key generated by the step without requiring a new
    # physically disconnected operating point to converge.
    actual=solver._newton;received=[]
    def capture(*args,**kwargs):
        received.append(kwargs['cache_key'])
        if change=='service':raise SolverConvergenceError('forced')
        return actual(*args,**kwargs)
    monkeypatch.setattr(solver,'_newton',capture)
    try:solver.step(state,h)
    except SolverConvergenceError:
        if change!='service':raise
    assert received and received[0]!=key

def test_retry_rolls_back_real_dsl_delay_and_all_buffers(monkeypatch):
    solver,state=smib(delta_offset=.02)
    device=solver.devices[0];device.memory=DSLMemory();device.expression=parse_expression('delay(u,0.04)')
    device.samples=deque([np.array([1.,2.])]);device.flags={'ready':True}
    original=solver._step_with_internal_events
    reference=copy.deepcopy(solver);expected,_=reference.step(state.copy(),.005)
    identities=(id(device),id(device.memory),id(device.samples),id(solver.network.ybus))
    oldx=state.x.copy();oldv=state.v.copy();failure_count=[]
    def rejected(current,h):
        if h>.005:
            device.memory.begin_accept()
            evaluate(device.expression,{'u':2.},time_s=current.t+h,runtime=device.memory)
            device.memory.finish_accept()
            device.samples[0][:]=99;device.samples.append(np.array([-7.]))
            device.flags['ready']=False;solver.network.ybus[:]=0
            current.x[:]=7;current.v[:]=0
            solver.internal_events.append({'tentative':True})
            failure_count.append(h)
            raise SolverConvergenceError('forced rejection with delay memory')
        return original(current,h)
    monkeypatch.setattr(solver,'_step_with_internal_events',rejected)
    solver.retry_steps=True;solver.min_step_s=.001
    solved,metric=solver.step(state,.02)
    assert failure_count==[.02,.01] and metric.step_s==.005
    np.testing.assert_array_equal(solved.x,expected.x)
    np.testing.assert_array_equal(solved.v,expected.v)
    np.testing.assert_array_equal(state.x,oldx);np.testing.assert_array_equal(state.v,oldv)
    assert not device.memory.records and device.memory.version==0
    assert device.flags=={'ready':True} and len(device.samples)==1
    np.testing.assert_array_equal(device.samples[0],[1.,2.])
    assert identities==(id(device),id(device.memory),id(device.samples),id(solver.network.ybus))
    assert len(solver.step_retries)==3 and not solver.internal_events

def test_retry_exhaustion_restores_initial_state(monkeypatch):
    solver,state=smib();before=state.copy();device=solver.devices[0];device.buffer=[]
    def reject(current,h):
        current.x[:]=123;device.buffer.append(h)
        raise SolverConvergenceError('forced')
    monkeypatch.setattr(solver,'_step_with_internal_events',reject)
    solver.retry_steps=True;solver.min_step_s=.005
    with pytest.raises(SolverConvergenceError,match='rms_retry_exhausted'):
        solver.step(state,.01)
    np.testing.assert_array_equal(state.x,before.x)
    assert device.buffer==[] and len(solver.step_retries)==2
    assert not solver._retry_active

