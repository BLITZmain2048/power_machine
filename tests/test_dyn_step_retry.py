def test_checkpoint_restores_slots_cycles_and_unset_attributes():
    from power_machine.dynamics.checkpoint import RuntimeCheckpoint
    class Buffer:
        __slots__=('values','late','parent')
    obj=Buffer();obj.values=[np.array([2.,3.])];obj.parent=obj
    checkpoint=RuntimeCheckpoint(obj)
    original=obj.values
    obj.values[0][:]=7.;obj.values.append(9);obj.late=True;obj.parent=None
    checkpoint.restore()
    assert obj.values is original and obj.parent is obj and not hasattr(obj,'late')
    assert len(obj.values)==1
    np.testing.assert_array_equal(obj.values[0],[2.,3.])


def test_native_control_cache_tracks_inputs_parameters_and_controller_identity():
    from types import SimpleNamespace
    from power_machine.dynamics.ieee39_native import NativeControlledMachine
    class AVR:
        n_states=1
        parameters={'gain':2.}
        calls=0
        def evaluate(self,t,x,inputs):
            self.calls+=1
            return {'Efd':self.parameters['gain']*inputs['Vref']}, np.array([x[0]+inputs['Vt']])
    machine=SimpleNamespace(object_id='M',relative_path='M',bus_id='B',n_states=2,
                            bus_un_kv=10.,ugn_kv=10.,ve=0.,pt=3.)
    avr=AVR();device=NativeControlledMachine(machine,avr=avr)
    device.avr_inputs={'Vref':1.}
    state=np.array([1.,0.,.3])
    first=device.controls(0.,state,1.)[0];first[:]=100.
    second=device.controls(0.,state,1.)[0]
    np.testing.assert_array_equal(second,[1.3]);assert avr.calls==1
    second[:]=-100.
    np.testing.assert_array_equal(device.controls(0.,state,1.)[0],[1.3])
    avr.parameters={'gain':3.};device.controls(0.,state,1.);assert avr.calls==2 and machine.ve==3.
    device.avr_inputs['Vref']=2.;device.controls(0.,state,1.);assert avr.calls==3 and machine.ve==6.
    replacement=AVR();replacement.parameters=avr.parameters.copy();device.avr=replacement
    device.controls(0.,state,1.);assert replacement.calls==1
    machine.pt=9.;device.controls(0.,state,1.);assert machine.pt==9.


